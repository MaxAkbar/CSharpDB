using System.Buffers.Binary;
using System.Security.Cryptography;

namespace CSharpDB.WalPrototype.Tests;

public sealed class ControlCodecTests
{
    internal static ControlRecord Record(ulong sequence = 1) => new(new(1, 2), sequence, 1,
        new(3, 4), ControlMode.Active, ControlCodec.DataStart, 3);

    internal static byte[] Header(ControlRecord first, ControlRecord second) =>
        [.. ControlCodec.Encode(first), .. ControlCodec.Encode(second)];

    [Fact]
    public void CanonicalLayout_MatchesIndependentLittleEndianVector()
    {
        var record = new ControlRecord(new(0x0807060504030201, 0x1817161514131211),
            0x0102030405060708, 0x0102030405060707, new(0x11223344, 0x55667788),
            ControlMode.Active, 16432, 0x12345678);
        byte[] encoded = ControlCodec.Encode(record);
        // Independently packed with Python struct + hashlib, not generated by this codec.
        Assert.Equal("4357413202000000000000000010000000100000181000000020000000000000" +
            "0102030405060708111213141516171808070605040302010707060504030201" +
            "4433221188776655010000000000000030400000000000007856341200000000",
            Convert.ToHexString(encoded.AsSpan(0, 96)));
        Assert.Equal("B565E41231C80C2A740D6C1BC85BC4EC79684D0CB43D353BBBE8D99EDE1FC986",
            Convert.ToHexString(encoded.AsSpan(ControlCodec.DigestOffset)));
        Assert.Equal(record, ControlCodec.Decode(encoded, 16432));
        Assert.Equal(encoded, ControlCodec.Encode(ControlCodec.Decode(encoded, 16432)!));
    }

    [Fact]
    public void EverySingleBitCorruption_IsUnavailable()
    {
        byte[] encoded = ControlCodec.Encode(Record());
        for (int i = 0; i < encoded.Length; i++)
            for (int bit = 0; bit < 8; bit++)
            {
                encoded[i] ^= (byte)(1 << bit);
                Assert.Null(ControlCodec.Decode(encoded, ControlCodec.DataStart));
                encoded[i] ^= (byte)(1 << bit);
            }
    }

    [Fact]
    public void EveryPrefixAndSuffixTear_EitherDetectsTearOrReadsExactOldOrNewRecord()
    {
        var old = Record();
        var next = old with { Sequence = 19, Epoch = 2, Salt = new(7, 8), Mode = ControlMode.Empty };
        byte[] oldBytes = ControlCodec.Encode(old), newBytes = ControlCodec.Encode(next);
        for (int cut = 0; cut <= ControlCodec.SlotSize; cut++)
        {
            byte[] prefix = (byte[])oldBytes.Clone(), suffix = (byte[])oldBytes.Clone();
            newBytes.AsSpan(0, cut).CopyTo(prefix);
            newBytes.AsSpan(cut).CopyTo(suffix.AsSpan(cut));
            foreach (byte[] bytes in new[] { prefix, suffix })
            {
                var decoded = ControlCodec.Decode(bytes, ControlCodec.DataStart);
                Assert.True(decoded is null || decoded == old || decoded == next, $"cut={cut}");
            }
        }
    }

    [Fact]
    public void All512ByteSectorSubsets_DetectTearOrReadExactRecord()
    {
        var old = Record();
        var next = old with { Sequence = 2, Floor = ControlCodec.DataStart + ControlCodec.FrameSize };
        byte[] oldBytes = ControlCodec.Encode(old), newBytes = ControlCodec.Encode(next);
        for (int mask = 0; mask < 256; mask++)
        {
            byte[] bytes = (byte[])oldBytes.Clone();
            for (int sector = 0; sector < 8; sector++)
                if ((mask & (1 << sector)) != 0)
                    newBytes.AsSpan(sector * 512, 512).CopyTo(bytes.AsSpan(sector * 512));
            var decoded = ControlCodec.Decode(bytes, next.Floor);
            Assert.True(decoded is null || decoded == old || decoded == next, $"mask={mask}");
        }
    }

    [Theory]
    [InlineData(0)] // magic
    [InlineData(4)] // version
    [InlineData(8)] // flags
    [InlineData(12)] // slot size
    [InlineData(16)] // page size
    [InlineData(20)] // frame size
    [InlineData(24)] // data start
    [InlineData(72)] // unknown mode (ACTIVE 1 XOR 0x80)
    [InlineData(76)] // reserved word
    [InlineData(92)] // reserved area
    [InlineData(4063)]
    public void ChecksummedUnsupportedSlot_NeverFallsBackToOtherSlot(int offset)
    {
        foreach (int badSlot in new[] { 0, 1 })
        {
            byte[] header = Header(Record(1), Record(2));
            var slot = header.AsSpan(badSlot * ControlCodec.SlotSize, ControlCodec.SlotSize);
            slot[offset] ^= 0x80;
            Rehash(slot);
            byte[] before = (byte[])header.Clone();
            Assert.Throws<InvalidDataException>(() => ControlCodec.Select(header, ControlCodec.DataStart));
            Assert.Equal(before, header);
        }
    }

    [Theory]
    [InlineData(0)]
    [InlineData(8191)]
    [InlineData(8193)]
    [InlineData(12312)] // aligned but beyond physical extent
    [InlineData(9223372036854775808UL)]
    [InlineData(18446744073709551615UL)]
    public void ChecksummedImpossibleFloor_IsFatalEvenInOlderSlot(ulong floor)
    {
        byte[] header = Header(Record(1), Record(2));
        BinaryPrimitives.WriteUInt64LittleEndian(header.AsSpan(80), floor);
        Rehash(header.AsSpan(0, ControlCodec.SlotSize));
        Assert.Throws<InvalidDataException>(() => ControlCodec.Select(header, ControlCodec.DataStart));
    }

    [Theory]
    [InlineData(32, 16)] // identity
    [InlineData(48, 8)] // sequence
    [InlineData(56, 8)] // epoch
    [InlineData(64, 4)] // first salt
    [InlineData(68, 4)] // second salt
    public void ChecksummedMissingRequiredField_IsFatal(int offset, int length)
    {
        byte[] header = Header(Record(1), Record(2));
        header.AsSpan(offset, length).Clear();
        Rehash(header.AsSpan(0, ControlCodec.SlotSize));
        Assert.Throws<InvalidDataException>(() => ControlCodec.Select(header, ControlCodec.DataStart));
    }

    [Fact]
    public void ConflictingIdentitiesSequencesSaltsOrRegressingState_AreFatal()
    {
        var first = Record(10) with { Floor = ControlCodec.DataStart + ControlCodec.FrameSize, Epoch = 2 };
        ControlRecord[] conflicts =
        [
            first with { Sequence = 11, Identity = new(5, 6) },
            first with { PageCount = 99 },
            first with { Sequence = 11, Salt = new(5, 6) },
            first with { Sequence = 11, Floor = ControlCodec.DataStart },
            first with { Sequence = 11, Epoch = 1, Salt = new(5, 6) },
            first with { Sequence = 11, Epoch = 3 },
            first with { Sequence = 11, Mode = ControlMode.Empty, Floor = ControlCodec.DataStart }
        ];
        foreach (var second in conflicts)
            Assert.Throws<InvalidDataException>(() => ControlCodec.Select(Header(first, second), first.Floor));
        Assert.True(ControlCodec.Select(Header(first, first), first.Floor).Mirrored);
    }

    [Fact]
    public void MissingSlotUsesPeer_BothMissingOrTruncatedControlAreaFail()
    {
        byte[] header = Header(Record(1), Record(2));
        foreach (int lost in new[] { 0, 1 })
        {
            byte[] bytes = (byte[])header.Clone();
            bytes.AsSpan(lost * ControlCodec.SlotSize, ControlCodec.SlotSize).Clear();
            var selected = ControlCodec.Select(bytes, ControlCodec.DataStart);
            Assert.Equal((ulong)(lost == 0 ? 2 : 1), selected.Current.Sequence);
            Assert.False(selected.Mirrored);
        }
        Assert.Throws<InvalidDataException>(() => ControlCodec.Select(new byte[8192], 8192));
        Assert.Throws<InvalidDataException>(() => ControlCodec.Select(header.AsSpan(0, 4096), 4096));
        for (int length = 0; length < 4096; length++)
            Assert.Null(ControlCodec.Decode(header.AsSpan(0, length), 8192));
    }

    [Fact]
    public void EmptyCannotPointIntoFrames_AndTailNeedNotBeAligned()
    {
        Assert.Throws<InvalidDataException>(() => ControlCodec.Encode(Record() with
        { Mode = ControlMode.Empty, Floor = ControlCodec.DataStart + ControlCodec.FrameSize }));
        var record = Record() with { Floor = ControlCodec.DataStart + ControlCodec.FrameSize };
        Assert.Equal(record, ControlCodec.Decode(ControlCodec.Encode(record), record.Floor + 13));
        var terminal = Record(ulong.MaxValue) with { Epoch = ulong.MaxValue, PageCount = uint.MaxValue };
        Assert.Equal(terminal, ControlCodec.Decode(ControlCodec.Encode(terminal), ControlCodec.DataStart));
    }

    [Fact]
    public void GeneratedIdentitiesAndSalts_AreNonzeroAndNew()
    {
        var salt = new GenerationSalt(3, 4);
        for (int i = 0; i < 100; i++)
        {
            Assert.NotEqual(default, FileIdentity.Create());
            var next = GenerationSalt.Create(salt);
            Assert.NotEqual(salt, next);
            Assert.NotEqual(0u, next.First);
            Assert.NotEqual(0u, next.Second);
            salt = next;
        }
    }

    private static void Rehash(Span<byte> bytes) =>
        SHA256.HashData(bytes[..ControlCodec.DigestOffset], bytes[ControlCodec.DigestOffset..]);
}
